-- =====================================================================
--  MDE Electromecánica · Sistema de Órdenes de Trabajo
--  Paso 21 · Chat interno
--   - Un chat General (lo leen y escriben todos) y chats privados entre dos personas.
--   - Contador de mensajes sin leer.
--   - Se usa solo con estas funciones: chat_conversaciones, chat_leer, chat_enviar, chat_sin_leer.
--  Se puede correr más de una vez sin problema.
-- =====================================================================
begin;

create table if not exists public.chat_mensajes (
  id         bigint generated by default as identity primary key,
  de         uuid not null references public.usuarios (id) default auth.uid(),
  para       uuid references public.usuarios (id),          -- null = chat General
  texto      text not null check (length(trim(texto)) between 1 and 2000),
  creado_en  timestamptz not null default now()
);
create index if not exists chat_mensajes_general on public.chat_mensajes (creado_en) where para is null;
create index if not exists chat_mensajes_privado on public.chat_mensajes (de, para, creado_en);

-- Hasta qué mensaje leyó cada uno en cada conversación ('general' o el id de la otra persona).
create table if not exists public.chat_leido (
  usuario_id    uuid not null references public.usuarios (id) on delete cascade,
  conversacion  text not null,
  leido_hasta   bigint not null default 0,
  primary key (usuario_id, conversacion)
);

alter table public.chat_mensajes enable row level security;
alter table public.chat_leido enable row level security;
-- Sin políticas: nadie lee ni escribe directo; todo pasa por las funciones de abajo.

-- ¿Puede usar el chat? (usuario activo con algún rol)
create or replace function public.chat_puede()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.usuarios u join public.usuario_roles r on r.usuario_id = u.id
                  where u.id = auth.uid() and u.activo and not coalesce(u.eliminado, false));
$$;

-- Lista de conversaciones: General primero, después cada persona activa (o con mensajes).
create or replace function public.chat_conversaciones()
returns table (conversacion text, nombre text, ultimo_texto text, ultimo_de text, ultimo_en timestamptz, sin_leer integer)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
declare v_yo uuid := auth.uid();
begin
  if not public.chat_puede() then raise exception 'No tenés acceso al chat'; end if;
  return query
  with ult as (
    select 'general'::text as conv, m.id, m.texto, m.de, m.creado_en from public.chat_mensajes m where m.para is null
    union all
    select (case when m.de = v_yo then m.para else m.de end)::text, m.id, m.texto, m.de, m.creado_en
      from public.chat_mensajes m where m.para is not null and (m.de = v_yo or m.para = v_yo)
  ), conv as (
    select 'general'::text as conv, 'General · todo el taller'::text as nombre, 0 as orden
    union all
    select u.id::text, u.nombre, 1 from public.usuarios u
     where u.id <> v_yo and (
       (u.activo and not coalesce(u.eliminado, false) and exists (select 1 from public.usuario_roles r where r.usuario_id = u.id))
       or exists (select 1 from ult where ult.conv = u.id::text))
  )
  select c.conv, c.nombre,
         (select ult.texto from ult where ult.conv = c.conv order by ult.id desc limit 1),
         (select us.nombre from ult join public.usuarios us on us.id = ult.de where ult.conv = c.conv order by ult.id desc limit 1),
         (select max(ult.creado_en) from ult where ult.conv = c.conv),
         (select count(*)::int from ult where ult.conv = c.conv and ult.de <> v_yo
             and ult.id > coalesce((select l.leido_hasta from public.chat_leido l where l.usuario_id = v_yo and l.conversacion = c.conv), 0))
    from conv c
   order by c.orden, (select max(ult.creado_en) from ult where ult.conv = c.conv) desc nulls last, c.nombre;
end $$;

-- Mensajes de una conversación (los últimos 200, o los nuevos desde p_desde). Marca como leídos.
create or replace function public.chat_leer(p_conversacion text, p_desde bigint default 0)
returns table (id bigint, de uuid, nombre text, texto text, creado_en timestamptz)
language plpgsql security definer set search_path = public as $$
#variable_conflict use_column
declare v_yo uuid := auth.uid(); v_otro uuid; v_max bigint;
begin
  if not public.chat_puede() then raise exception 'No tenés acceso al chat'; end if;
  if p_conversacion <> 'general' then v_otro := p_conversacion::uuid; end if;
  select max(m.id) into v_max from public.chat_mensajes m
   where (v_otro is null and m.para is null)
      or (v_otro is not null and ((m.de = v_yo and m.para = v_otro) or (m.de = v_otro and m.para = v_yo)));
  if v_max is not null then
    insert into public.chat_leido (usuario_id, conversacion, leido_hasta) values (v_yo, p_conversacion, v_max)
    on conflict (usuario_id, conversacion) do update set leido_hasta = greatest(chat_leido.leido_hasta, excluded.leido_hasta);
  end if;
  return query
  select x.id, x.de, x.nombre, x.texto, x.creado_en from (
    select m.id, m.de, u.nombre, m.texto, m.creado_en
      from public.chat_mensajes m join public.usuarios u on u.id = m.de
     where m.id > coalesce(p_desde, 0)
       and ((v_otro is null and m.para is null)
         or (v_otro is not null and ((m.de = v_yo and m.para = v_otro) or (m.de = v_otro and m.para = v_yo))))
     order by m.id desc limit 200) x
  order by x.id;
end $$;

create or replace function public.chat_enviar(p_conversacion text, p_texto text)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_otro uuid; v_id bigint;
begin
  if not public.chat_puede() then raise exception 'No tenés acceso al chat'; end if;
  if nullif(trim(p_texto), '') is null then raise exception 'Escribí un mensaje'; end if;
  if length(trim(p_texto)) > 2000 then raise exception 'El mensaje es muy largo (máximo 2000 letras)'; end if;
  if p_conversacion <> 'general' then
    v_otro := p_conversacion::uuid;
    if v_otro = auth.uid() then raise exception 'No podés escribirte a vos mismo'; end if;
    if not exists (select 1 from public.usuarios where id = v_otro and activo and not coalesce(eliminado, false)) then
      raise exception 'Esa persona ya no está activa';
    end if;
  end if;
  insert into public.chat_mensajes (de, para, texto) values (auth.uid(), v_otro, trim(p_texto)) returning id into v_id;
  insert into public.chat_leido (usuario_id, conversacion, leido_hasta) values (auth.uid(), p_conversacion, v_id)
  on conflict (usuario_id, conversacion) do update set leido_hasta = greatest(chat_leido.leido_hasta, excluded.leido_hasta);
  return v_id;
end $$;

-- Total de mensajes sin leer (para el contador).
create or replace function public.chat_sin_leer()
returns integer language sql stable security definer set search_path = public as $$
  select case when not public.chat_puede() then 0 else (
    select count(*)::int from public.chat_mensajes m
     where m.de <> auth.uid()
       and (m.para is null or m.para = auth.uid())
       and m.id > coalesce((select l.leido_hasta from public.chat_leido l
                             where l.usuario_id = auth.uid()
                               and l.conversacion = case when m.para is null then 'general' else m.de::text end), 0)) end;
$$;

revoke all on public.chat_mensajes, public.chat_leido from anon;
revoke execute on function public.chat_puede(), public.chat_conversaciones(), public.chat_leer(text, bigint),
  public.chat_enviar(text, text), public.chat_sin_leer() from public, anon;
grant execute on function public.chat_puede(), public.chat_conversaciones(), public.chat_leer(text, bigint),
  public.chat_enviar(text, text), public.chat_sin_leer() to authenticated;

commit;

notify pgrst, 'reload schema';

select 'Paso 21 listo: chat interno' as resultado;
