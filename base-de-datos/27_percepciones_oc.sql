-- =====================================================================
--  MDE Electromecánica · Sistema de Órdenes de Trabajo
--  Paso 27 · Compras: percepciones y retenciones en la orden de compra
--   - A cada OC se le pueden agregar los regímenes que cobra el proveedor
--     (percepción de IIBB, percepción de IVA, impuestos internos, etc.):
--       · como % sobre el subtotal sin IVA, o
--       · como importe fijo en $.
--   - Se suman al total de la OC (en pantalla, en la lista y en la OC impresa).
--   - Se cargan al armar el borrador y también después de emitida o recibida
--     (por ejemplo cuando llega la factura del proveedor). Queda en el historial.
--     Si alguien que no es el Administrador las cambia en una OC ya aprobada,
--     le llega un aviso al Administrador con el total anterior y el nuevo.
--  Correr después del paso 26. Se puede correr más de una vez sin problema.
-- =====================================================================
begin;

-- ---------------------------------------------------------------------
-- 1. Tabla
-- ---------------------------------------------------------------------
create table if not exists public.ordenes_compra_percepciones (
  id        bigint generated by default as identity primary key,
  oc_id     bigint not null references public.ordenes_compra (id) on delete cascade,
  renglon   integer not null,
  concepto  text not null check (trim(concepto) <> ''),
  tipo      text not null default 'PORCENTAJE',     -- PORCENTAJE (sobre el subtotal sin IVA) o IMPORTE ($ fijo)
  alicuota  numeric(7,3),                           -- % cuando es PORCENTAJE
  importe   numeric(14,2),                          -- $ cuando es IMPORTE
  constraint oc_percepcion_tipo check (tipo in ('PORCENTAJE', 'IMPORTE')),
  constraint oc_percepcion_valor check (
    (tipo = 'PORCENTAJE' and alicuota > 0 and alicuota <= 100 and importe is null) or
    (tipo = 'IMPORTE' and importe > 0 and alicuota is null))
);
create index if not exists oc_percepciones_oc on public.ordenes_compra_percepciones (oc_id, renglon);

-- ---------------------------------------------------------------------
-- 2. Importes (la app los lee como columnas: importe_percepciones, importe_total)
-- ---------------------------------------------------------------------
create or replace function public.importe_percepciones(o public.ordenes_compra)
returns numeric language sql stable set search_path = public as $$
  select coalesce(sum(case when p.tipo = 'PORCENTAJE' then round(public.importe_neto(o) * p.alicuota / 100, 2)
                           else p.importe end), 0)
  from public.ordenes_compra_percepciones p where p.oc_id = o.id;
$$;

create or replace function public.importe_total(o public.ordenes_compra)
returns numeric language sql stable set search_path = public as $$
  select public.importe_neto(o) + public.importe_iva(o) + public.importe_percepciones(o);
$$;

-- "PERCEPCIÓN IIBB NEUQUÉN 3 % $ 1.267,65; IMPUESTOS INTERNOS $ 500,00" (o "ninguna")
create or replace function public.oc_percepciones_texto(p_oc bigint)
returns text language sql stable security definer set search_path = public as $$
  select coalesce(string_agg(p.concepto
           || case when p.tipo = 'PORCENTAJE' then ' ' || public.num_texto(p.alicuota) || ' %' else '' end
           || ' ' || public.pesos(case when p.tipo = 'PORCENTAJE' then round(public.importe_neto(o) * p.alicuota / 100, 2)
                                       else p.importe end),
           '; ' order by p.renglon), 'ninguna')
  from public.ordenes_compra o
  left join public.ordenes_compra_percepciones p on p.oc_id = o.id
  where o.id = p_oc;
$$;

-- Reemplaza las percepciones de una OC.
--   p_lista: [{"concepto": "Percepción IIBB Neuquén", "tipo": "PORCENTAJE", "alicuota": 3},
--             {"concepto": "Impuestos internos", "tipo": "IMPORTE", "importe": 1500}]
create or replace function public.oc_reemplazar_percepciones(p_oc bigint, p_lista jsonb)
returns void language plpgsql security definer set search_path = public as $$
declare x jsonb; v_n integer := 0; v_conc text; v_tipo text; v_alic numeric; v_imp numeric;
begin
  if p_lista is null or jsonb_typeof(p_lista) = 'null' then p_lista := '[]'::jsonb; end if;
  if jsonb_typeof(p_lista) <> 'array' then raise exception 'Las percepciones no tienen el formato correcto'; end if;
  delete from public.ordenes_compra_percepciones where oc_id = p_oc;
  for x in select * from jsonb_array_elements(p_lista) loop
    v_n := v_n + 1;
    v_conc := nullif(upper(regexp_replace(trim(coalesce(x ->> 'concepto', '')), '\s+', ' ', 'g')), '');
    if v_conc is null then raise exception 'Percepción %: escribí el concepto (ej.: Percepción IIBB)', v_n; end if;
    v_tipo := upper(coalesce(nullif(trim(x ->> 'tipo'), ''), 'PORCENTAJE'));
    if v_tipo not in ('PORCENTAJE', 'IMPORTE') then raise exception 'Percepción % (%): tipo inválido', v_n, v_conc; end if;
    if v_tipo = 'PORCENTAJE' then
      v_alic := nullif(x ->> 'alicuota', '')::numeric;
      if v_alic is null or v_alic <= 0 or v_alic > 100 then
        raise exception 'Percepción % (%): el porcentaje tiene que ser mayor a 0 y hasta 100', v_n, v_conc;
      end if;
      if v_alic <> round(v_alic, 3) then
        raise exception 'Percepción % (%): el porcentaje admite hasta 3 decimales', v_n, v_conc;
      end if;
      v_imp := null;
    else
      v_imp := nullif(x ->> 'importe', '')::numeric;
      if v_imp is null or v_imp <= 0 then
        raise exception 'Percepción % (%): el importe tiene que ser mayor a cero', v_n, v_conc;
      end if;
      v_imp := round(v_imp, 2);
      v_alic := null;
    end if;
    insert into public.ordenes_compra_percepciones (oc_id, renglon, concepto, tipo, alicuota, importe)
    values (p_oc, v_n, v_conc, v_tipo, v_alic, v_imp);
  end loop;
end $$;

-- ---------------------------------------------------------------------
-- 3. Guardar el borrador (igual que en el paso 26, más las percepciones)
--   p_datos puede traer "percepciones": [...]. Si no lo trae, no se tocan.
-- ---------------------------------------------------------------------
create or replace function public.guardar_oc(p_id bigint, p_datos jsonb, p_lineas jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_oc public.ordenes_compra; v_prov bigint; v_destino text; v_ot bigint; v_ot_estado text;
  l jsonb; v_n integer := 0; v_cod text; v_desc text; v_cant numeric; v_precio numeric; v_iva numeric;
  v_ped bigint; p public.pedidos_repuesto; v_otra integer; v_perc integer;
begin
  perform public.oc_controlar_armado();
  if p_lineas is null or jsonb_typeof(p_lineas) <> 'array' or jsonb_array_length(p_lineas) = 0 then
    raise exception 'Agregá al menos un renglón a la orden de compra';
  end if;
  v_prov := nullif(p_datos ->> 'proveedor_id', '')::bigint;
  if v_prov is null then raise exception 'Elegí el proveedor'; end if;
  if not exists (select 1 from public.proveedores where id = v_prov) then raise exception 'El proveedor no existe'; end if;
  v_destino := upper(coalesce(nullif(trim(p_datos ->> 'destino'), ''), 'OT'));
  if v_destino not in ('OT', 'STOCK', 'INSUMOS') then raise exception 'Destino inválido: %', v_destino; end if;
  if v_destino = 'OT' then
    v_ot := nullif(p_datos ->> 'ot_id', '')::bigint;
    if v_ot is null then raise exception 'Elegí la OT a la que va la compra'; end if;
    select estado::text into v_ot_estado from public.ordenes_trabajo where id = v_ot;
    if v_ot_estado is null then raise exception 'La OT no existe'; end if;
  end if;

  if p_id is null then
    if v_ot_estado in ('CERRADA', 'FACTURADA', 'PRUEBA') then
      raise exception 'La OT está %: no se le pueden hacer compras', lower(v_ot_estado);
    end if;
    if not exists (select 1 from public.proveedores where id = v_prov and activo) then
      raise exception 'Ese proveedor está desactivado';
    end if;
    insert into public.ordenes_compra (destino, ot_id, proveedor_id, entrega_estimada, condicion_pago, observaciones)
    values (v_destino, v_ot, v_prov, nullif(p_datos ->> 'entrega_estimada', '')::date,
            nullif(trim(p_datos ->> 'condicion_pago'), ''), nullif(trim(p_datos ->> 'observaciones'), ''))
    returning * into v_oc;
  else
    select * into v_oc from public.ordenes_compra where id = p_id for update;
    if v_oc.id is null then raise exception 'La orden de compra no existe'; end if;
    if v_oc.estado <> 'BORRADOR' then
      raise exception 'Solo se puede modificar una orden de compra en borrador (esta está %)', lower(v_oc.estado);
    end if;
    if v_ot is distinct from v_oc.ot_id and v_ot_estado in ('CERRADA', 'FACTURADA', 'PRUEBA') then
      raise exception 'La OT está %: no se le pueden hacer compras', lower(v_ot_estado);
    end if;
    if v_prov <> v_oc.proveedor_id and not exists (select 1 from public.proveedores where id = v_prov and activo) then
      raise exception 'Ese proveedor está desactivado';
    end if;
    update public.ordenes_compra
       set destino = v_destino, ot_id = v_ot, proveedor_id = v_prov,
           entrega_estimada = nullif(p_datos ->> 'entrega_estimada', '')::date,
           condicion_pago = nullif(trim(p_datos ->> 'condicion_pago'), ''),
           observaciones = nullif(trim(p_datos ->> 'observaciones'), '')
     where id = p_id
    returning * into v_oc;
    delete from public.ordenes_compra_lineas where oc_id = p_id;   -- en borrador no hay nada recibido
  end if;

  for l in select * from jsonb_array_elements(p_lineas) loop
    v_n := v_n + 1;
    v_cod := null;
    v_desc := nullif(upper(regexp_replace(trim(coalesce(l ->> 'descripcion', '')), '\s+', ' ', 'g')), '');
    if nullif(trim(coalesce(l ->> 'codigo', '')), '') is not null then
      select r.codigo, coalesce(v_desc, r.descripcion) into v_cod, v_desc
        from public.repuestos r
       where r.codigo_limpio = upper(regexp_replace(l ->> 'codigo', '\s+', '', 'g')) and not r.eliminado;
      if v_cod is null then raise exception 'Renglón %: no existe el repuesto %', v_n, l ->> 'codigo'; end if;
    end if;
    if v_desc is null then raise exception 'Renglón %: escribí qué se compra', v_n; end if;
    v_cant := nullif(l ->> 'cantidad', '')::numeric;
    if v_cant is null or v_cant <= 0 then
      raise exception 'Renglón % (%): la cantidad tiene que ser mayor a cero', v_n, v_desc;
    end if;
    v_precio := nullif(l ->> 'precio_unitario', '')::numeric;
    if v_precio < 0 then raise exception 'Renglón % (%): el precio no puede ser negativo', v_n, v_desc; end if;
    v_iva := coalesce(nullif(l ->> 'alicuota_iva', '')::numeric, 21);
    if v_iva not in (0, 10.5, 21, 27) then
      raise exception 'Renglón % (%): el IVA tiene que ser 0, 10,5, 21 o 27 %%', v_n, v_desc;
    end if;
    v_ped := nullif(l ->> 'pedido_id', '')::bigint;
    if v_ped is not null then
      select * into p from public.pedidos_repuesto where id = v_ped;
      if p.id is null or v_destino <> 'OT' or p.ot_id <> v_ot then
        raise exception 'Renglón % (%): ese pedido de repuesto no es de esta OT', v_n, v_desc;
      end if;
      if p.estado <> 'PENDIENTE' then
        raise exception 'Renglón % (%): ese pedido de repuesto ya no está pendiente', v_n, v_desc;
      end if;
      -- Un pedido va en una sola OC (salvo que esa OC se haya anulado o cerrado con faltante).
      v_otra := null;
      select o.numero into v_otra
        from public.ordenes_compra_lineas x join public.ordenes_compra o on o.id = x.oc_id
       where x.pedido_id = v_ped and o.id <> v_oc.id and o.estado <> 'ANULADA' and o.cerrada_en is null limit 1;
      if v_otra is not null then
        raise exception 'Renglón % (%): ese pedido ya está en la %', v_n, v_desc, public.numero_oc_texto(v_otra);
      end if;
    end if;
    insert into public.ordenes_compra_lineas (oc_id, renglon, codigo, descripcion, cantidad, precio_unitario, alicuota_iva, pedido_id)
    values (v_oc.id, v_n, v_cod, v_desc, v_cant, v_precio, v_iva, v_ped);
  end loop;

  if p_datos ? 'percepciones' then
    perform public.oc_reemplazar_percepciones(v_oc.id, p_datos -> 'percepciones');
  end if;
  select count(*) into v_perc from public.ordenes_compra_percepciones where oc_id = v_oc.id;

  perform public.oc_anotar(v_oc.id, case when p_id is null then 'CREADA' else 'MODIFICADA' end,
    format('%s renglón(es)%s · total %s', v_n,
           case when v_perc > 0 then format(' · %s percepción(es)', v_perc) else '' end,
           public.pesos(public.oc_total(v_oc.id))));
  return v_oc.id;
end $$;

-- ---------------------------------------------------------------------
-- 4. Datos que se completan en cualquier momento (menos anulada):
--    factura, entrega estimada, observaciones y ahora también percepciones.
-- ---------------------------------------------------------------------
create or replace function public.modificar_oc_datos(p_id bigint, p_datos jsonb)
returns void language plpgsql security definer set search_path = public as $$
declare
  v public.ordenes_compra; v_fac text; v_ent date; v_obs text; v_cambios text := '';
  v_total_antes numeric; v_total_despues numeric; v_perc_antes text; v_perc_despues text;
begin
  perform public.oc_controlar_armado();
  select * into v from public.ordenes_compra where id = p_id for update;
  if v.id is null then raise exception 'La orden de compra no existe'; end if;
  if v.estado = 'ANULADA' then raise exception 'La orden de compra está anulada'; end if;
  v_fac := case when p_datos ? 'nro_factura' then nullif(trim(p_datos ->> 'nro_factura'), '') else v.nro_factura end;
  v_ent := case when p_datos ? 'entrega_estimada' then nullif(p_datos ->> 'entrega_estimada', '')::date else v.entrega_estimada end;
  v_obs := case when p_datos ? 'observaciones' then nullif(trim(p_datos ->> 'observaciones'), '') else v.observaciones end;
  if v_fac is distinct from v.nro_factura then
    v_cambios := v_cambios || format('; factura "%s" → "%s"', coalesce(v.nro_factura, ''), coalesce(v_fac, ''));
  end if;
  if v_ent is distinct from v.entrega_estimada then
    v_cambios := v_cambios || format('; entrega estimada %s → %s',
      coalesce(to_char(v.entrega_estimada, 'DD/MM/YYYY'), '—'), coalesce(to_char(v_ent, 'DD/MM/YYYY'), '—'));
  end if;
  if v_obs is distinct from v.observaciones then v_cambios := v_cambios || '; observaciones'; end if;
  if v_cambios <> '' then
    update public.ordenes_compra set nro_factura = v_fac, entrega_estimada = v_ent, observaciones = v_obs where id = p_id;
    perform public.oc_anotar(p_id, 'DATOS', 'Cambió ' || substr(v_cambios, 3));
  end if;

  if p_datos ? 'percepciones' then
    v_total_antes := public.oc_total(p_id);
    v_perc_antes := public.oc_percepciones_texto(p_id);
    perform public.oc_reemplazar_percepciones(p_id, p_datos -> 'percepciones');
    v_perc_despues := public.oc_percepciones_texto(p_id);
    if v_perc_despues is distinct from v_perc_antes then
      v_total_despues := public.oc_total(p_id);
      update public.ordenes_compra set actualizado_en = now() where id = p_id;
      perform public.oc_anotar(p_id, 'PERCEPCIONES',
        format('%s → %s · total %s → %s', v_perc_antes, v_perc_despues, public.pesos(v_total_antes), public.pesos(v_total_despues)));
      -- En una OC ya aprobada, si no lo hizo el Administrador, se le avisa.
      if v.estado in ('EMITIDA', 'RECIBIDA PARCIAL', 'RECIBIDA') and not public.es_admin() then
        insert into public.avisos (para_rol, tipo, mensaje, ot_id, oc_id, creado_por)
        values ('ADMINISTRADOR', 'OC PERCEPCIONES',
                format('%s cambió las percepciones de la %s: el total pasó de %s a %s',
                       coalesce(public.nombre_visible_de(auth.uid()), 'Alguien'), public.oc_resumen(p_id),
                       public.pesos(v_total_antes), public.pesos(v_total_despues)),
                v.ot_id, p_id, auth.uid());
      end if;
    end if;
  end if;
end $$;

-- ---------------------------------------------------------------------
-- 5. Permisos: se ven igual que la OC; nadie escribe directo.
-- ---------------------------------------------------------------------
alter table public.ordenes_compra_percepciones enable row level security;
drop policy if exists ver on public.ordenes_compra_percepciones;
create policy ver on public.ordenes_compra_percepciones for select to authenticated using (public.ve_todas_las_ot());
revoke all on public.ordenes_compra_percepciones from anon;
revoke insert, update, delete, truncate on public.ordenes_compra_percepciones from authenticated;
grant select on public.ordenes_compra_percepciones to authenticated;

revoke execute on function public.oc_reemplazar_percepciones(bigint, jsonb) from public, anon, authenticated;
revoke execute on function public.importe_percepciones(public.ordenes_compra), public.oc_percepciones_texto(bigint),
  public.importe_total(public.ordenes_compra), public.guardar_oc(bigint, jsonb, jsonb), public.modificar_oc_datos(bigint, jsonb)
  from public, anon;
grant execute on function public.importe_percepciones(public.ordenes_compra), public.oc_percepciones_texto(bigint),
  public.importe_total(public.ordenes_compra), public.guardar_oc(bigint, jsonb, jsonb), public.modificar_oc_datos(bigint, jsonb)
  to authenticated;

commit;

notify pgrst, 'reload schema';

