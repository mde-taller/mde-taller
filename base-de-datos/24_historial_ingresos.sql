-- =====================================================================
--  MDE Electromecánica · Sistema de Órdenes de Trabajo
--  Paso 24 · Historial de ingresos de stock
--   - Cada "Ingreso por lote" queda guardado como un ingreso (fecha, quién, observación/remito)
--     con sus renglones (repuesto, cantidad, observación).
--   - Los ingresos anteriores se agrupan solos (por fecha y usuario de carga).
--   - Depósito y Administrador pueden modificar un ingreso: cambiar la observación, la cantidad
--     de un renglón, quitar o agregar renglones, o eliminarlo entero. Nunca puede quedar stock negativo.
--   - Cada cambio queda anotado en el historial del ingreso.
--  Se puede correr más de una vez sin problema.
-- =====================================================================
begin;

create table if not exists public.ingresos_stock (
  id              bigint generated by default as identity primary key,
  creado_en       timestamptz not null default now(),
  creado_por      uuid references public.usuarios (id) default auth.uid(),
  usuario_nombre  text,          -- solo para ingresos traídos del Excel
  observacion     text,          -- remito, proveedor
  modificado_en   timestamptz,
  modificado_por  uuid references public.usuarios (id)
);
create index if not exists ingresos_stock_fecha on public.ingresos_stock (creado_en desc);

create table if not exists public.ingresos_stock_cambios (
  id          bigint generated by default as identity primary key,
  ingreso_id  bigint not null references public.ingresos_stock (id) on delete cascade,
  creado_en   timestamptz not null default now(),
  usuario_id  uuid references public.usuarios (id) default auth.uid(),
  detalle     text not null
);
create index if not exists ingresos_stock_cambios_ingreso on public.ingresos_stock_cambios (ingreso_id, creado_en);

alter table public.movimientos_stock add column if not exists ingreso_id bigint references public.ingresos_stock (id) on delete cascade;
create index if not exists movimientos_ingreso on public.movimientos_stock (ingreso_id);

-- Ingresos anteriores: un ingreso por cada carga (misma fecha y mismo usuario).
insert into public.ingresos_stock (creado_en, creado_por, usuario_nombre, observacion)
select m.fecha, m.usuario_id, m.usuario_nombre,
       case when count(distinct coalesce(m.observacion, '')) = 1 then max(m.observacion) end
  from public.movimientos_stock m
 where m.tipo = 'ENTRADA' and m.ingreso_id is null
 group by m.fecha, m.usuario_id, m.usuario_nombre;
update public.movimientos_stock m
   set ingreso_id = i.id
  from public.ingresos_stock i
 where m.tipo = 'ENTRADA' and m.ingreso_id is null
   and i.creado_en = m.fecha and i.creado_por is not distinct from m.usuario_id
   and i.usuario_nombre is not distinct from m.usuario_nombre
   and not exists (select 1 from public.ingresos_stock_cambios c where c.ingreso_id = i.id);

-- Permisos: ven los que ven el stock; nadie escribe directo (todo por las funciones de abajo).
alter table public.ingresos_stock enable row level security;
alter table public.ingresos_stock_cambios enable row level security;
drop policy if exists ver on public.ingresos_stock;
create policy ver on public.ingresos_stock for select to authenticated using (public.ve_todas_las_ot());
drop policy if exists ver on public.ingresos_stock_cambios;
create policy ver on public.ingresos_stock_cambios for select to authenticated using (public.ve_todas_las_ot());
revoke all on public.ingresos_stock, public.ingresos_stock_cambios from anon;
grant select on public.ingresos_stock, public.ingresos_stock_cambios to authenticated;

-- ---------- Funciones internas ----------
create or replace function public.ingreso_puede()
returns void language plpgsql stable security definer set search_path = public as $$
begin
  if not (public.tiene_rol('DEPOSITO') or public.es_admin()) then
    raise exception 'Solo Depósito o Administrador pueden cargar o modificar ingresos';
  end if;
end $$;

create or replace function public.ingreso_anotar(p_ingreso bigint, p_detalle text)
returns void language sql security definer set search_path = public as $$
  insert into public.ingresos_stock_cambios (ingreso_id, detalle) values (p_ingreso, p_detalle);
  update public.ingresos_stock set modificado_en = now(), modificado_por = auth.uid() where id = p_ingreso;
$$;

-- Busca el repuesto por código (con o sin espacios); error si no existe o fue eliminado.
create or replace function public.ingreso_codigo(p_codigo text)
returns text language plpgsql stable security definer set search_path = public as $$
declare v text;
begin
  select codigo into v from public.repuestos
   where codigo_limpio = upper(regexp_replace(coalesce(p_codigo, ''), '\s+', '', 'g')) and not eliminado;
  if v is null then raise exception 'No existe el repuesto %', p_codigo; end if;
  return v;
end $$;

-- ---------- Registrar un ingreso nuevo ----------
-- p_items: [{"codigo": "...", "cantidad": 2, "observacion": "..."}]
create or replace function public.registrar_ingreso(p_observacion text, p_items jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_id bigint; it jsonb; v_cod text; v_cant numeric; v_n integer := 0;
begin
  perform public.ingreso_puede();
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'El ingreso no tiene renglones'; end if;
  insert into public.ingresos_stock (observacion) values (nullif(trim(p_observacion), '')) returning id into v_id;
  for it in select * from jsonb_array_elements(p_items) loop
    v_cod := public.ingreso_codigo(it ->> 'codigo');
    v_cant := (it ->> 'cantidad')::numeric;
    if v_cant is null or v_cant <= 0 then raise exception 'Cantidad inválida para %', v_cod; end if;
    insert into public.movimientos_stock (tipo, codigo, cantidad, observacion, ingreso_id)
    values ('ENTRADA', v_cod, v_cant, coalesce(nullif(trim(it ->> 'observacion'), ''), nullif(trim(p_observacion), '')), v_id);
    v_n := v_n + 1;
  end loop;
  return v_id;
end $$;

-- ---------- Modificar ----------
create or replace function public.modificar_ingreso(p_id bigint, p_observacion text)
returns void language plpgsql security definer set search_path = public as $$
declare v_antes text;
begin
  perform public.ingreso_puede();
  select observacion into v_antes from public.ingresos_stock where id = p_id;
  if not found then raise exception 'El ingreso no existe'; end if;
  if coalesce(v_antes, '') is distinct from coalesce(nullif(trim(p_observacion), ''), '') then
    update public.ingresos_stock set observacion = nullif(trim(p_observacion), '') where id = p_id;
    perform public.ingreso_anotar(p_id, format('Observación: "%s" → "%s"', coalesce(v_antes, ''), coalesce(nullif(trim(p_observacion), ''), '')));
  end if;
end $$;

create or replace function public.modificar_ingreso_linea(p_mov_id bigint, p_cantidad numeric, p_observacion text default null)
returns void language plpgsql security definer set search_path = public as $$
declare m public.movimientos_stock; v_desc text;
begin
  perform public.ingreso_puede();
  select * into m from public.movimientos_stock where id = p_mov_id and tipo = 'ENTRADA' and ingreso_id is not null for update;
  if m.id is null then raise exception 'El renglón no existe'; end if;
  if p_cantidad is null or p_cantidad <= 0 then raise exception 'La cantidad tiene que ser mayor a cero (para sacarlo, usá Quitar)'; end if;
  perform 1 from public.repuestos where codigo = m.codigo for update;
  if public.stock_de(m.codigo) - m.cantidad + p_cantidad < 0 then
    raise exception 'No se puede: el stock de % quedaría negativo (hay %; ya se usó parte de este ingreso)',
      m.codigo, public.num_texto(public.stock_de(m.codigo));
  end if;
  update public.movimientos_stock set cantidad = p_cantidad, observacion = nullif(trim(p_observacion), '') where id = p_mov_id;
  select descripcion into v_desc from public.repuestos where codigo = m.codigo;
  if p_cantidad <> m.cantidad then
    perform public.ingreso_anotar(m.ingreso_id, format('%s (%s): cantidad %s → %s', v_desc, m.codigo, public.num_texto(m.cantidad), public.num_texto(p_cantidad)));
  end if;
  if coalesce(m.observacion, '') is distinct from coalesce(nullif(trim(p_observacion), ''), '') then
    perform public.ingreso_anotar(m.ingreso_id, format('%s (%s): observación "%s" → "%s"', v_desc, m.codigo, coalesce(m.observacion, ''), coalesce(nullif(trim(p_observacion), ''), '')));
  end if;
end $$;

create or replace function public.agregar_ingreso_linea(p_ingreso_id bigint, p_codigo text, p_cantidad numeric, p_observacion text default null)
returns void language plpgsql security definer set search_path = public as $$
declare v_cod text; v_desc text;
begin
  perform public.ingreso_puede();
  if not exists (select 1 from public.ingresos_stock where id = p_ingreso_id) then raise exception 'El ingreso no existe'; end if;
  v_cod := public.ingreso_codigo(p_codigo);
  if p_cantidad is null or p_cantidad <= 0 then raise exception 'La cantidad tiene que ser mayor a cero'; end if;
  insert into public.movimientos_stock (tipo, codigo, cantidad, observacion, ingreso_id)
  values ('ENTRADA', v_cod, p_cantidad, nullif(trim(p_observacion), ''), p_ingreso_id);
  select descripcion into v_desc from public.repuestos where codigo = v_cod;
  perform public.ingreso_anotar(p_ingreso_id, format('Agregó %s (%s) x %s', v_desc, v_cod, public.num_texto(p_cantidad)));
end $$;

create or replace function public.quitar_ingreso_linea(p_mov_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare m public.movimientos_stock; v_desc text;
begin
  perform public.ingreso_puede();
  select * into m from public.movimientos_stock where id = p_mov_id and tipo = 'ENTRADA' and ingreso_id is not null for update;
  if m.id is null then raise exception 'El renglón no existe'; end if;
  perform 1 from public.repuestos where codigo = m.codigo for update;
  if public.stock_de(m.codigo) - m.cantidad < 0 then
    raise exception 'No se puede quitar: el stock de % quedaría negativo (hay %; ya se usó parte de este ingreso)',
      m.codigo, public.num_texto(public.stock_de(m.codigo));
  end if;
  delete from public.movimientos_stock where id = p_mov_id;
  select descripcion into v_desc from public.repuestos where codigo = m.codigo;
  perform public.ingreso_anotar(m.ingreso_id, format('Quitó %s (%s) x %s', v_desc, m.codigo, public.num_texto(m.cantidad)));
end $$;

create or replace function public.eliminar_ingreso(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare r record;
begin
  perform public.ingreso_puede();
  if not exists (select 1 from public.ingresos_stock where id = p_id) then raise exception 'El ingreso no existe'; end if;
  for r in select codigo, sum(cantidad) as cant from public.movimientos_stock where ingreso_id = p_id group by codigo loop
    perform 1 from public.repuestos where codigo = r.codigo for update;
    if public.stock_de(r.codigo) - r.cant < 0 then
      raise exception 'No se puede eliminar: el stock de % quedaría negativo (hay %; ya se usó parte de este ingreso)',
        r.codigo, public.num_texto(public.stock_de(r.codigo));
    end if;
  end loop;
  delete from public.ingresos_stock where id = p_id;   -- borra también sus renglones y su historial
end $$;

revoke execute on function public.ingreso_puede(), public.ingreso_anotar(bigint, text), public.ingreso_codigo(text)
  from public, anon, authenticated;
revoke execute on function public.registrar_ingreso(text, jsonb), public.modificar_ingreso(bigint, text),
  public.modificar_ingreso_linea(bigint, numeric, text), public.agregar_ingreso_linea(bigint, text, numeric, text),
  public.quitar_ingreso_linea(bigint), public.eliminar_ingreso(bigint) from public, anon;
grant execute on function public.registrar_ingreso(text, jsonb), public.modificar_ingreso(bigint, text),
  public.modificar_ingreso_linea(bigint, numeric, text), public.agregar_ingreso_linea(bigint, text, numeric, text),
  public.quitar_ingreso_linea(bigint), public.eliminar_ingreso(bigint) to authenticated;

commit;

notify pgrst, 'reload schema';

select 'Paso 24 listo: historial de ingresos de stock' as resultado;
