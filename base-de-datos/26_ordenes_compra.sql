-- Volver a borrador para corregir: desde PARA APROBAR (quien la arma) o desde EMITIDA sin nada recibido (Administrador).
create or replace function public.volver_oc_a_borrador(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare v public.ordenes_compra;
begin
  perform public.oc_controlar_armado();
  select * into v from public.ordenes_compra where id = p_id for update;
  if v.id is null then raise exception 'La orden de compra no existe'; end if;
  if v.estado = 'EMITIDA' then
    if not public.es_admin() then
      raise exception 'Solo el Administrador puede volver a borrador una orden de compra emitida';
    end if;
    if exists (select 1 from public.ordenes_compra_recepciones where oc_id = p_id) then
      raise exception 'Ya tiene mercadería recibida: no se puede volver a borrador';
    end if;
  elsif v.estado <> 'PARA APROBAR' then
    raise exception 'No se puede volver a borrador una orden de compra %', lower(v.estado);
  end if;
  update public.ordenes_compra set estado = 'BORRADOR', aprobada_por = null, aprobada_en = null where id = p_id;
  perform public.oc_anotar(p_id, 'VUELTA A BORRADOR', null);
  if v.estado = 'EMITIDA' then
    insert into public.avisos (para_rol, tipo, mensaje, ot_id, oc_id)
    values ('DEPOSITO', 'OC EN CORRECCIÓN',
            format('La %s volvió a borrador para corregirla: no la recibas hasta que se vuelva a emitir.', public.oc_resumen(p_id)),
            v.ot_id, p_id);
  end if;
end $$;

