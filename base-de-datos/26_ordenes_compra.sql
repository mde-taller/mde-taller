-- El Administrador aprueba (desde borrador o para aprobar): pasa a EMITIDA.
create or replace function public.aprobar_oc(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare v public.ordenes_compra; r uuid;
begin
  if not public.es_admin() then raise exception 'Solo el Administrador aprueba órdenes de compra'; end if;
  select * into v from public.ordenes_compra where id = p_id for update;
  if v.id is null then raise exception 'La orden de compra no existe'; end if;
  if v.estado not in ('BORRADOR', 'PARA APROBAR') then
    raise exception 'La orden de compra ya fue aprobada o anulada (está %)', lower(v.estado);
  end if;
  if v.destino = 'OT' and v.ot_id is null then raise exception 'La OT de esta orden de compra ya no existe'; end if;
  perform public.oc_validar(p_id);
  update public.ordenes_compra
     set estado = 'EMITIDA', aprobada_por = auth.uid(), aprobada_en = now(),
         enviada_por = coalesce(enviada_por, auth.uid()), enviada_en = coalesce(enviada_en, now())
   where id = p_id;
  perform public.oc_anotar(p_id, 'APROBADA', 'Emitida por ' || public.pesos(public.oc_total(p_id)));
  for r in select distinct x from unnest(array[v.creado_por, v.enviada_por]) as x
            where x is not null and x is distinct from auth.uid() loop
    insert into public.avisos (para_usuario, tipo, mensaje, ot_id, oc_id)
    values (r, 'OC APROBADA', format('Se aprobó la %s. Ya se puede mandar al proveedor.', public.oc_resumen(p_id)), v.ot_id, p_id);
  end loop;
  insert into public.avisos (para_rol, tipo, mensaje, ot_id, oc_id)
  values ('DEPOSITO', 'OC EMITIDA',
          format('Se emitió la %s. Va a llegar: %s', public.oc_resumen(p_id), public.oc_items_texto(p_id)), v.ot_id, p_id);
end $$;

