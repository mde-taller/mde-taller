-- Recibir mercadería (Depósito o Administrador), todo o una parte.
--   p_items: [{"linea_id": 10, "cantidad": 2}, {"linea_id": 11, "cantidad": 1}]
create or replace function public.recibir_oc(p_id bigint, p_remito text, p_items jsonb, p_observacion text default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v public.ordenes_compra; l public.ordenes_compra_lineas; it jsonb;
  v_rec bigint; v_ing bigint; v_ped bigint; v_cant numeric; v_n integer := 0;
  v_prov text; v_ot_estado text; v_obs text; v_remito text := nullif(trim(p_remito), '');
  v_lista text := ''; v_entregar text := ''; v_quedan text := ''; v_item text;
begin
  perform public.ingreso_puede();   -- Depósito o Administrador
  select * into v from public.ordenes_compra where id = p_id for update;
  if v.id is null then raise exception 'La orden de compra no existe'; end if;
  if v.estado not in ('EMITIDA', 'RECIBIDA PARCIAL') then
    raise exception 'Solo se recibe mercadería de una orden de compra emitida (esta está %)', lower(v.estado);
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' then raise exception 'Indicá qué llegó'; end if;
  select nombre into v_prov from public.proveedores where id = v.proveedor_id;
  if v.destino = 'OT' then
    select estado::text into v_ot_estado from public.ordenes_trabajo where id = v.ot_id;
  end if;
  v_obs := public.numero_oc_texto(v.numero) || ' · ' || v_prov || coalesce(' · Remito ' || v_remito, '');

  insert into public.ordenes_compra_recepciones (oc_id, remito, observacion)
  values (p_id, v_remito, nullif(trim(p_observacion), ''))
  returning id into v_rec;

  perform set_config('mde.oc_recepcion', '1', true);
  for it in select * from jsonb_array_elements(p_items) loop
    v_cant := coalesce(nullif(it ->> 'cantidad', '')::numeric, 0);
    if v_cant = 0 then continue; end if;
    select * into l from public.ordenes_compra_lineas
     where id = nullif(it ->> 'linea_id', '')::bigint and oc_id = p_id for update;
    if l.id is null then raise exception 'Uno de los renglones no es de esta orden de compra'; end if;
    if v_cant < 0 then raise exception 'Renglón % (%): la cantidad no puede ser negativa', l.renglon, l.descripcion; end if;
    if v_cant > l.cantidad - l.cantidad_recibida then
      raise exception 'Renglón % (%): llegan % pero faltaban recibir %', l.renglon, l.descripcion,
        public.num_texto(v_cant), public.num_texto(l.cantidad - l.cantidad_recibida);
    end if;
    v_n := v_n + 1;
    v_item := l.descripcion || ' x ' || public.num_texto(v_cant);
    update public.ordenes_compra_lineas set cantidad_recibida = cantidad_recibida + v_cant where id = l.id;
    v_ped := null;
    if l.codigo is not null then
      -- Entra al stock (un solo ingreso por recepción).
      if v_ing is null then
        insert into public.ingresos_stock (observacion) values (v_obs) returning id into v_ing;
      end if;
      insert into public.movimientos_stock (tipo, codigo, cantidad, observacion, ingreso_id)
      values ('ENTRADA', l.codigo, v_cant, v_obs, v_ing);
      -- Para una OT: queda pedido a Depósito para entregar.
      if v.destino = 'OT' and v.ot_id is not null then
        if l.pedido_id is not null and exists (select 1 from public.pedidos_repuesto where id = l.pedido_id and estado = 'PENDIENTE') then
          v_ped := l.pedido_id;           -- ya estaba pedido para la OT
          v_entregar := v_entregar || '; ' || v_item;
        elsif v_ot_estado not in ('CERRADA', 'FACTURADA', 'PRUEBA') then
          insert into public.pedidos_repuesto (ot_id, codigo, descripcion, cantidad, pedido_por, detalle)
          values (v.ot_id, l.codigo, l.descripcion, v_cant, v.creado_por,
                  'Llegó por la ' || public.numero_oc_texto(v.numero) || ' (' || v_prov || ')')
          returning id into v_ped;
          v_entregar := v_entregar || '; ' || v_item;
        else
          v_quedan := v_quedan || '; ' || v_item;
        end if;
      end if;
    end if;
    insert into public.ordenes_compra_recepcion_items (recepcion_id, linea_id, cantidad, pedido_id)
    values (v_rec, l.id, v_cant, v_ped);
    v_lista := v_lista || '; ' || v_item;
  end loop;
  perform set_config('mde.oc_recepcion', '', true);

  if v_n = 0 then raise exception 'Indicá la cantidad de al menos un renglón que llegó'; end if;
  update public.ordenes_compra_recepciones set ingreso_id = v_ing where id = v_rec;
  perform public.oc_recalcular_estado(p_id);
  perform public.oc_anotar(p_id, 'RECEPCIÓN', substr(v_lista, 3) || coalesce(' · Remito ' || v_remito, ''));

  if v_entregar <> '' then
    insert into public.avisos (para_rol, tipo, mensaje, ot_id, oc_id, creado_por)
    values ('DEPOSITO', 'OC RECIBIDA',
            format('Llegó mercadería de la %s: %s. Ya está en stock: entregala a la OT.', public.oc_resumen(p_id), substr(v_entregar, 3)),
            v.ot_id, p_id, auth.uid());
  end if;
  if v_quedan <> '' then
    insert into public.avisos (para_rol, tipo, mensaje, ot_id, oc_id, creado_por)
    values ('DEPOSITO', 'OC RECIBIDA',
            format('Llegó mercadería de la %s, pero la OT está %s: quedó en stock. %s', public.oc_resumen(p_id),
                   lower(v_ot_estado), substr(v_quedan, 3)),
            v.ot_id, p_id, auth.uid());
  end if;
  return v_rec;
end $$;

-- Anular una recepción cargada por error: vuelve el stock y lo recibido. No se puede si ya se entregó a la OT.
create or replace function public.anular_recepcion_oc(p_recepcion_id bigint, p_motivo text)
returns void language plpgsql security definer set search_path = public as $$
declare r public.ordenes_compra_recepciones; v public.ordenes_compra; x record; v_detalle text;
begin
  perform public.ingreso_puede();
  if nullif(trim(p_motivo), '') is null then raise exception 'Escribí por qué se anula la recepción'; end if;
  select * into r from public.ordenes_compra_recepciones where id = p_recepcion_id;
  if r.id is null then raise exception 'La recepción no existe'; end if;
  select * into v from public.ordenes_compra where id = r.oc_id for update;

  -- Lo que se pidió para la OT al recibir: si Depósito ya lo entregó (todo o una parte), no se puede.
  for x in
    select l.descripcion, i.cantidad, p.estado as ped_estado, p.cantidad as ped_cantidad
      from public.ordenes_compra_recepcion_items i
      join public.ordenes_compra_lineas l on l.id = i.linea_id
      join public.pedidos_repuesto p on p.id = i.pedido_id
     where i.recepcion_id = r.id and i.pedido_id is distinct from l.pedido_id
  loop
    if x.ped_estado = 'RESUELTO' or (x.ped_estado = 'PENDIENTE' and x.ped_cantidad < x.cantidad) then
      raise exception '% ya se entregó (todo o una parte) a la OT: quitalo de la OT antes de anular la recepción', x.descripcion;
    end if;
  end loop;

  -- El stock no puede quedar negativo.
  for x in
    select l.codigo, sum(i.cantidad) as cantidad
      from public.ordenes_compra_recepcion_items i join public.ordenes_compra_lineas l on l.id = i.linea_id
     where i.recepcion_id = r.id and l.codigo is not null
     group by l.codigo
  loop
    perform 1 from public.repuestos where codigo = x.codigo for update;
    if public.stock_de(x.codigo) - x.cantidad < 0 then
      raise exception 'No se puede anular: el stock de % quedaría negativo (hay %; ya se usó parte de lo recibido)',
        x.codigo, public.num_texto(public.stock_de(x.codigo));
    end if;
  end loop;

  select string_agg(l.descripcion || ' x ' || public.num_texto(i.cantidad), '; ' order by l.renglon) into v_detalle
    from public.ordenes_compra_recepcion_items i join public.ordenes_compra_lineas l on l.id = i.linea_id
   where i.recepcion_id = r.id;

  -- Los pedidos que se habían creado para la OT al recibir se cancelan.
  update public.pedidos_repuesto p
     set estado = 'CANCELADO', resuelto_por = auth.uid(), resuelto_en = now(),
         nota = 'Se anuló la recepción de la ' || public.numero_oc_texto(v.numero)
    from public.ordenes_compra_recepcion_items i
    join public.ordenes_compra_lineas l on l.id = i.linea_id
   where i.recepcion_id = r.id and p.id = i.pedido_id and i.pedido_id is distinct from l.pedido_id and p.estado = 'PENDIENTE';

  update public.ordenes_compra_lineas l
     set cantidad_recibida = l.cantidad_recibida - s.cantidad
    from (select linea_id, sum(cantidad) as cantidad from public.ordenes_compra_recepcion_items
           where recepcion_id = r.id group by linea_id) s
   where l.id = s.linea_id;

  perform set_config('mde.oc_recepcion', '1', true);
  if r.ingreso_id is not null then
    delete from public.ingresos_stock where id = r.ingreso_id;   -- borra sus movimientos: vuelve el stock
  end if;
  perform set_config('mde.oc_recepcion', '', true);
  delete from public.ordenes_compra_recepciones where id = r.id;

  update public.ordenes_compra set cerrada_en = null, cerrada_por = null, motivo_cierre = null where id = v.id;
  perform public.oc_recalcular_estado(v.id);
  perform public.oc_anotar(v.id, 'RECEPCIÓN ANULADA',
    coalesce(v_detalle, '') || coalesce(' · Remito ' || r.remito, '') || ' · ' || trim(p_motivo));
end $$;

-- Cerrar con faltante: llegó una parte y el resto no va a llegar.
create or replace function public.cerrar_oc_con_faltante(p_id bigint, p_motivo text)
returns void language plpgsql security definer set search_path = public as $$
declare v public.ordenes_compra; v_falta text;
begin
  perform public.oc_controlar_armado();
  if nullif(trim(p_motivo), '') is null then raise exception 'Escribí por qué se cierra con faltante'; end if;
  select * into v from public.ordenes_compra where id = p_id for update;
  if v.id is null then raise exception 'La orden de compra no existe'; end if;
  if v.estado <> 'RECIBIDA PARCIAL' then
    raise exception 'Solo se cierra con faltante una orden de compra recibida en parte (si no llegó nada, anulala)';
  end if;
  v_falta := public.oc_items_texto(p_id, true);
  update public.ordenes_compra set cerrada_en = now(), cerrada_por = auth.uid(), motivo_cierre = trim(p_motivo) where id = p_id;
  perform public.oc_recalcular_estado(p_id);
  perform public.oc_anotar(p_id, 'CERRADA CON FALTANTE', trim(p_motivo) || coalesce(' · No llegó: ' || v_falta, ''));
end $$;

