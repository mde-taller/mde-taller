create or replace function public.numero_oc_texto(p_numero integer)
returns text language sql stable security definer set search_path = public as $$
  select coalesce((select valor from public.configuracion where clave = 'prefijo_oc'), 'OC-')
         || lpad(p_numero::text, 6, '0');
$$;

-- Importe legible: 1234.5 → "$ 1.234,50"
create or replace function public.pesos(v numeric)
returns text language sql immutable as $$
  select '$ ' || translate(to_char(coalesce(v, 0), 'FM999,999,999,990.00'), ',.', '.,');
$$;

-- Importes de una OC (la app los lee como columnas: importe_neto, importe_iva, importe_total).
-- El IVA se calcula por alícuota sobre el neto de cada alícuota, como en una factura.
create or replace function public.importe_neto(o public.ordenes_compra)
returns numeric language sql stable set search_path = public as $$
  select coalesce(sum(round(l.cantidad * coalesce(l.precio_unitario, 0), 2)), 0)
  from public.ordenes_compra_lineas l where l.oc_id = o.id;
$$;

create or replace function public.importe_iva(o public.ordenes_compra)
returns numeric language sql stable set search_path = public as $$
  select coalesce(sum(x.iva), 0) from (
    select round(sum(round(l.cantidad * coalesce(l.precio_unitario, 0), 2)) * l.alicuota_iva / 100, 2) as iva
    from public.ordenes_compra_lineas l where l.oc_id = o.id group by l.alicuota_iva) x;
$$;

create or replace function public.importe_total(o public.ordenes_compra)
returns numeric language sql stable set search_path = public as $$
  select public.importe_neto(o) + public.importe_iva(o);
$$;

create or replace function public.oc_total(p_oc bigint)
returns numeric language sql stable security definer set search_path = public as $$
  select public.importe_total(o) from public.ordenes_compra o where o.id = p_oc;
$$;

-- "OC-000012 (PROVEEDOR) para OT-001463 · AG798BW"
create or replace function public.oc_resumen(p_oc bigint)
returns text language sql stable security definer set search_path = public as $$
  select public.numero_oc_texto(o.numero) || ' (' || p.nombre || ')'
         || case o.destino
              when 'OT' then coalesce(' para ' || public.numero_ot_texto(t.numero) || coalesce(' · ' || u.dominio, ''), '')
              when 'STOCK' then ' para stock'
              else ' para insumos del taller' end
  from public.ordenes_compra o
  join public.proveedores p on p.id = o.proveedor_id
  left join public.ordenes_trabajo t on t.id = o.ot_id
  left join public.unidades u on u.id = t.unidad_id
  where o.id = p_oc;
$$;

-- "FILTRO DE ACEITE (A123) x 2; TORNEAR CAMPANA x 1"
create or replace function public.oc_items_texto(p_oc bigint, p_solo_pendiente boolean default false)
returns text language sql stable security definer set search_path = public as $$
  select string_agg(l.descripcion || coalesce(' (' || l.codigo || ')', '') || ' x '
                    || public.num_texto(case when p_solo_pendiente then l.cantidad - l.cantidad_recibida else l.cantidad end),
                    '; ' order by l.renglon)
  from public.ordenes_compra_lineas l
  where l.oc_id = p_oc and (not p_solo_pendiente or l.cantidad_recibida < l.cantidad);
$$;

create or replace function public.oc_controlar_armado()
returns void language plpgsql stable security definer set search_path = public as $$
begin
  if not public.ve_todas_las_ot() then
    raise exception 'Solo Oficina, Depósito o Administrador pueden manejar órdenes de compra';
  end if;
end $$;

create or replace function public.oc_anotar(p_oc bigint, p_tipo text, p_detalle text)
returns void language sql security definer set search_path = public as $$
  insert into public.ordenes_compra_historial (oc_id, tipo, detalle, usuario_id) values (p_oc, p_tipo, p_detalle, auth.uid());
$$;

-- Antes de aprobar: tiene renglones y todos tienen precio.
create or replace function public.oc_validar(p_oc bigint)
returns void language plpgsql stable security definer set search_path = public as $$
declare v_sin text;
begin
  if not exists (select 1 from public.ordenes_compra_lineas where oc_id = p_oc) then
    raise exception 'La orden de compra no tiene renglones';
  end if;
  select string_agg(renglon || '. ' || descripcion, ', ' order by renglon) into v_sin
    from public.ordenes_compra_lineas where oc_id = p_oc and precio_unitario is null;
  if v_sin is not null then
    raise exception 'Falta el precio en: %', v_sin;
  end if;
end $$;

-- Estado según lo recibido (solo para OC ya emitidas).
create or replace function public.oc_recalcular_estado(p_oc bigint)
returns text language plpgsql security definer set search_path = public as $$
declare v_estado text; v_cerrada timestamptz; v_rec numeric; v_completa boolean;
begin
  select estado, cerrada_en into v_estado, v_cerrada from public.ordenes_compra where id = p_oc;
  if v_estado not in ('EMITIDA', 'RECIBIDA PARCIAL', 'RECIBIDA') then return v_estado; end if;
  select coalesce(sum(cantidad_recibida), 0), coalesce(bool_and(cantidad_recibida >= cantidad), false)
    into v_rec, v_completa
    from public.ordenes_compra_lineas where oc_id = p_oc;
  v_estado := case when v_completa or (v_cerrada is not null and v_rec > 0) then 'RECIBIDA'
                   when v_rec > 0 then 'RECIBIDA PARCIAL'
                   else 'EMITIDA' end;
  update public.ordenes_compra set estado = v_estado where id = p_oc and estado is distinct from v_estado;
  return v_estado;
end $$;

-- Número correlativo y fecha del día (hora de Argentina).
create or replace function public.oc_antes_de_guardar()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_inicial integer;
begin
  if tg_op = 'INSERT' then
    if new.numero is null then
      perform pg_advisory_xact_lock(hashtext('numero_oc'));
      select nullif(trim(valor), '')::integer into v_inicial from public.configuracion where clave = 'nro_oc_inicial';
      select greatest(coalesce(max(numero), 0) + 1, coalesce(v_inicial, 1)) into new.numero from public.ordenes_compra;
    end if;
    new.fecha := coalesce(new.fecha, (now() at time zone 'America/Argentina/Buenos_Aires')::date);
    new.creado_por := coalesce(new.creado_por, auth.uid());
  end if;
  new.actualizado_en := now();
  return new;
end $$;

drop trigger if exists oc_antes_de_guardar on public.ordenes_compra;
create trigger oc_antes_de_guardar
  before insert or update on public.ordenes_compra
  for each row execute function public.oc_antes_de_guardar();

-- Los ingresos de stock que vienen de una OC no se modifican desde Stock (se corrigen desde la OC).
create or replace function public.oc_bloquear_ingreso_manual()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_ing bigint; v_ing2 bigint; v_num integer;
begin
  if coalesce(current_setting('mde.oc_recepcion', true), '') <> '1' then
    if tg_table_name = 'ingresos_stock' then
      v_ing := old.id;                                   -- solo UPDATE y DELETE
    else
      if tg_op in ('UPDATE', 'DELETE') then v_ing := old.ingreso_id; end if;
      if tg_op in ('INSERT', 'UPDATE') then v_ing2 := new.ingreso_id; end if;
    end if;
    if v_ing is not null or v_ing2 is not null then
      select o.numero into v_num
        from public.ordenes_compra_recepciones r join public.ordenes_compra o on o.id = r.oc_id
       where r.ingreso_id in (v_ing, v_ing2) limit 1;
      if v_num is not null then
        raise exception 'Este ingreso viene de la %: para corregirlo, anulá la recepción desde la orden de compra',
          public.numero_oc_texto(v_num);
      end if;
    end if;
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end $$;

drop trigger if exists oc_bloquear_ingreso on public.ingresos_stock;
create trigger oc_bloquear_ingreso
  before update or delete on public.ingresos_stock
  for each row execute function public.oc_bloquear_ingreso_manual();
drop trigger if exists oc_bloquear_movimiento on public.movimientos_stock;
create trigger oc_bloquear_movimiento
  before insert or update or delete on public.movimientos_stock
  for each row execute function public.oc_bloquear_ingreso_manual();

