-- =====================================================================
--  MDE Electromecánica · Sistema de Órdenes de Trabajo
--  Paso 26 · Compras: proveedores y órdenes de compra
--   - Proveedores: nombre, CUIT, teléfono, email, contacto, dirección y condición de pago.
--   - Orden de compra (OC-000001) a un proveedor, con destino:
--       · una OT (una OT puede tener varias OC),
--       · Stock, o
--       · Insumos del taller.
--     Renglones: repuesto de la lista o texto libre (ej. tornería), cantidad,
--     precio unitario SIN IVA y alícuota de IVA (0, 10,5, 21 o 27 %). Total con IVA.
--   - Circuito: BORRADOR → PARA APROBAR → EMITIDA → RECIBIDA PARCIAL → RECIBIDA (o ANULADA).
--       · Oficina, Depósito y Administrador la arman y la envían a aprobar.
--       · El Administrador la aprueba (pasa a EMITIDA) o la rechaza con motivo (vuelve a BORRADOR).
--   - Recepción (Depósito o Administrador), total o por partes, con N° de remito:
--       · Lo que tiene código de la lista entra al stock como un ingreso ("OC-000001 · PROVEEDOR · Remito …").
--       · Si la OC es para una OT, queda como pedido de repuesto pendiente de esa OT y se le avisa
--         a Depósito para que lo entregue, con el mismo botón "Entregar" de siempre.
--       · Lo escrito a mano (servicios, insumos sin código) solo queda registrado como recibido.
--       · Una recepción se puede anular (vuelve el stock) si todavía no se entregó a la OT.
--       · Los ingresos de stock que vienen de una OC no se tocan desde Stock: se corrigen desde la OC.
--   - Todo queda en el historial de la OC. Los avisos llevan enlace a la OC.
--  Se puede correr más de una vez sin problema.
-- =====================================================================
begin;

-- ---------------------------------------------------------------------
-- 1. Proveedores
-- ---------------------------------------------------------------------
create table if not exists public.proveedores (
  id              bigint generated by default as identity primary key,
  nombre          text not null check (trim(nombre) <> ''),
  cuit            text,
  telefono        text,
  email           text,
  direccion       text,
  contacto        text,
  condicion_pago  text,          -- se propone al armar una OC
  observaciones   text,
  activo          boolean not null default true,
  creado_por      uuid references public.usuarios (id) default auth.uid(),
  creado_en       timestamptz not null default now()
);
create unique index if not exists proveedores_nombre_unico on public.proveedores (upper(trim(nombre)));
create unique index if not exists proveedores_cuit_unico on public.proveedores ((regexp_replace(cuit, '\D', '', 'g')))
  where regexp_replace(coalesce(cuit, ''), '\D', '', 'g') <> '';

-- Nombre en mayúsculas, CUIT con formato 30-12345678-9, campos vacíos como "sin dato".
create or replace function public.proveedor_antes_de_guardar()
returns trigger language plpgsql set search_path = public as $$
declare v_cuit text;
begin
  new.nombre := upper(regexp_replace(trim(new.nombre), '\s+', ' ', 'g'));
  v_cuit := regexp_replace(coalesce(new.cuit, ''), '\D', '', 'g');
  if v_cuit = '' then
    new.cuit := null;
  elsif length(v_cuit) <> 11 then
    raise exception 'El CUIT tiene que tener 11 números';
  else
    new.cuit := substr(v_cuit, 1, 2) || '-' || substr(v_cuit, 3, 8) || '-' || substr(v_cuit, 11, 1);
  end if;
  new.telefono       := nullif(trim(new.telefono), '');
  new.email          := nullif(lower(trim(new.email)), '');
  new.direccion      := nullif(trim(new.direccion), '');
  new.contacto       := nullif(trim(new.contacto), '');
  new.condicion_pago := nullif(trim(new.condicion_pago), '');
  new.observaciones  := nullif(trim(new.observaciones), '');
  return new;
end $$;

drop trigger if exists proveedor_antes_de_guardar on public.proveedores;
create trigger proveedor_antes_de_guardar
  before insert or update on public.proveedores
  for each row execute function public.proveedor_antes_de_guardar();

-- ---------------------------------------------------------------------
-- 2. Órdenes de compra
-- ---------------------------------------------------------------------
create table if not exists public.ordenes_compra (
  id                bigint generated by default as identity primary key,
  numero            integer not null unique,                 -- se asigna solo (correlativo)
  estado            text not null default 'BORRADOR',
  destino           text not null default 'OT',              -- OT, STOCK o INSUMOS
  ot_id             bigint references public.ordenes_trabajo (id) on delete set null,
  proveedor_id      bigint not null references public.proveedores (id),
  fecha             date not null,
  entrega_estimada  date,
  condicion_pago    text,
  observaciones     text,
  nro_factura       text,                                    -- factura del proveedor
  creado_por        uuid references public.usuarios (id),
  creado_en         timestamptz not null default now(),
  enviada_por       uuid references public.usuarios (id),
  enviada_en        timestamptz,
  aprobada_por      uuid references public.usuarios (id),
  aprobada_en       timestamptz,
  cerrada_por       uuid references public.usuarios (id),    -- cerrada con faltante
  cerrada_en        timestamptz,
  motivo_cierre     text,
  anulada_por       uuid references public.usuarios (id),
  anulada_en        timestamptz,
  motivo_anulacion  text,
  actualizado_en    timestamptz not null default now(),
  constraint oc_estado_valido check (estado in ('BORRADOR', 'PARA APROBAR', 'EMITIDA', 'RECIBIDA PARCIAL', 'RECIBIDA', 'ANULADA')),
  constraint oc_destino_valido check (destino in ('OT', 'STOCK', 'INSUMOS')),
  -- Con destino OT tiene que tener OT (si se elimina la OT, solo puede quedar una OC anulada).
  constraint oc_ot_segun_destino check (
    (destino = 'OT' and (ot_id is not null or estado = 'ANULADA')) or (destino <> 'OT' and ot_id is null))
);
create index if not exists oc_ot on public.ordenes_compra (ot_id);
create index if not exists oc_estado on public.ordenes_compra (estado);
create index if not exists oc_proveedor on public.ordenes_compra (proveedor_id);

create table if not exists public.ordenes_compra_lineas (
  id                 bigint generated by default as identity primary key,
  oc_id              bigint not null references public.ordenes_compra (id) on delete cascade,
  renglon            integer not null,
  codigo             text references public.repuestos (codigo) on update cascade,   -- vacío si es texto libre
  descripcion        text not null check (trim(descripcion) <> ''),
  cantidad           numeric(12,2) not null check (cantidad > 0),
  precio_unitario    numeric(14,2) check (precio_unitario >= 0),                     -- SIN IVA
  alicuota_iva       numeric(5,2) not null default 21 check (alicuota_iva in (0, 10.5, 21, 27)),
  cantidad_recibida  numeric(12,2) not null default 0,
  pedido_id          bigint references public.pedidos_repuesto (id) on delete set null,  -- pedido de la OT que cubre
  constraint oc_linea_recibida_valida check (cantidad_recibida >= 0 and cantidad_recibida <= cantidad)
);
create index if not exists oc_lineas_oc on public.ordenes_compra_lineas (oc_id, renglon);
create index if not exists oc_lineas_pedido on public.ordenes_compra_lineas (pedido_id) where pedido_id is not null;
create index if not exists oc_lineas_codigo on public.ordenes_compra_lineas (codigo) where codigo is not null;

create table if not exists public.ordenes_compra_recepciones (
  id           bigint generated by default as identity primary key,
  oc_id        bigint not null references public.ordenes_compra (id) on delete cascade,
  remito       text,
  observacion  text,
  ingreso_id   bigint references public.ingresos_stock (id) on delete set null,   -- ingreso de stock que generó
  creado_por   uuid references public.usuarios (id) default auth.uid(),
  creado_en    timestamptz not null default now()
);
create index if not exists oc_recepciones_oc on public.ordenes_compra_recepciones (oc_id);
create index if not exists oc_recepciones_ingreso on public.ordenes_compra_recepciones (ingreso_id) where ingreso_id is not null;

create table if not exists public.ordenes_compra_recepcion_items (
  id            bigint generated by default as identity primary key,
  recepcion_id  bigint not null references public.ordenes_compra_recepciones (id) on delete cascade,
  linea_id      bigint not null references public.ordenes_compra_lineas (id) on delete cascade,
  cantidad      numeric(12,2) not null check (cantidad > 0),
  pedido_id     bigint references public.pedidos_repuesto (id) on delete set null   -- pedido de la OT para entregar
);
create index if not exists oc_recepcion_items_recepcion on public.ordenes_compra_recepcion_items (recepcion_id);

create table if not exists public.ordenes_compra_historial (
  id          bigint generated by default as identity primary key,
  oc_id       bigint not null references public.ordenes_compra (id) on delete cascade,
  creado_en   timestamptz not null default now(),
  usuario_id  uuid references public.usuarios (id) default auth.uid(),
  tipo        text not null,
  detalle     text
);
create index if not exists oc_historial_oc on public.ordenes_compra_historial (oc_id, creado_en);

