-- Cada vez que se crea un usuario en Supabase (Authentication) se crea su ficha.
-- El nombre se toma de los datos del usuario ("nombre") o, si no hay, del email.
create or replace function public.crear_ficha_usuario()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.usuarios (id, nombre)
  values (new.id, coalesce(nullif(trim(new.raw_user_meta_data ->> 'nombre'), ''),
                           split_part(new.email, '@', 1)))
  on conflict (id) do nothing;
  return new;
end $$;

create trigger al_crear_usuario
  after insert on auth.users
  for each row execute function public.crear_ficha_usuario();

-- ¿El usuario conectado tiene este rol?
create or replace function public.tiene_rol(r public.rol_usuario)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1
    from public.usuario_roles ur
    join public.usuarios u on u.id = ur.usuario_id
    where ur.usuario_id = auth.uid() and ur.rol = r and u.activo
  );
$$;

create or replace function public.es_admin()
returns boolean language sql stable as $$ select public.tiene_rol('ADMINISTRADOR') $$;

create or replace function public.es_oficina_o_admin()
returns boolean language sql stable as $$
  select public.tiene_rol('OFICINA') or public.tiene_rol('ADMINISTRADOR')
$$;

-- Administrador, Oficina y Depósito ven todas las OT; el mecánico solo las suyas.
create or replace function public.ve_todas_las_ot()
returns boolean language sql stable as $$
  select public.tiene_rol('ADMINISTRADOR') or public.tiene_rol('OFICINA') or public.tiene_rol('DEPOSITO')
$$;

