-- 9. Tiempos reales (control interno)
-- ---------------------------------------------------------------------
create table public.registros_tiempo (
  id           bigint generated by default as identity primary key,
  tarea_id     bigint not null references public.tareas_ot (id) on delete cascade,
  mecanico_id  uuid not null references public.usuarios (id),
  inicio       timestamptz not null default now(),
  fin          timestamptz,
  check (fin is null or fin >= inicio)
);
-- Un mecánico no puede tener dos cronómetros abiertos en la misma tarea.
create unique index un_cronometro_abierto
  on public.registros_tiempo (tarea_id, mecanico_id) where fin is null;

create view public.horas_reales with (security_invoker = true) as
select rt.tarea_id,
       t.ot_id,
       rt.mecanico_id,
       u.nombre as mecanico,
       round(sum(extract(epoch from (coalesce(rt.fin, now()) - rt.inicio))) / 3600.0, 2) as horas_reales,
       bool_or(rt.fin is null) as en_curso
from public.registros_tiempo rt
join public.tareas_ot t on t.id = rt.tarea_id
join public.usuarios u on u.id = rt.mecanico_id
group by rt.tarea_id, t.ot_id, rt.mecanico_id, u.nombre;

