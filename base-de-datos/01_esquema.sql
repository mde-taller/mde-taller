-- Funciones auxiliares para el mecánico
create or replace function public.mecanico_en_tarea(p_tarea_id bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.asignaciones where tarea_id = p_tarea_id and mecanico_id = auth.uid());
$$;

create or replace function public.mecanico_en_ot(p_ot_id bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.asignaciones a join public.tareas_ot t on t.id = a.tarea_id
    where t.ot_id = p_ot_id and a.mecanico_id = auth.uid()
  );
$$;

