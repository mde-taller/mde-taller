-- Número de OT con prefijo (ej. OT-001401)
create or replace function public.numero_ot_texto(p_numero integer)
returns text language sql stable security definer set search_path = public as $$
  select coalesce((select valor from public.configuracion where clave = 'prefijo_ot'), '')
         || lpad(p_numero::text, 6, '0');
$$;

-- OT: número correlativo, cliente desde la unidad, fecha de ingreso fija.
create or replace function public.antes_de_guardar_ot()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_inicial integer;
begin
  if tg_op = 'INSERT' then
    if new.numero is null then
      perform pg_advisory_xact_lock(hashtext('numero_ot'));
      select nullif(valor, '')::integer into v_inicial
        from public.configuracion where clave = 'nro_ot_inicial';
      select greatest(coalesce(max(numero), 0) + 1, coalesce(v_inicial, 1))
        into new.numero from public.ordenes_trabajo;
    end if;
    select cliente_id into new.cliente_id from public.unidades where id = new.unidad_id;
    new.creado_por := coalesce(new.creado_por, auth.uid());
  else
    -- La fecha de ingreso queda congelada (solo el Administrador puede corregirla).
    if new.fecha_ingreso is distinct from old.fecha_ingreso and not public.es_admin() then
      new.fecha_ingreso := old.fecha_ingreso;
    end if;
    if new.unidad_id is distinct from old.unidad_id then
      select cliente_id into new.cliente_id from public.unidades where id = new.unidad_id;
    end if;
    new.actualizado_en := now();
  end if;
  return new;
end $$;

create trigger ot_antes_de_guardar
  before insert or update on public.ordenes_trabajo
  for each row execute function public.antes_de_guardar_ot();

-- La unidad recuerda su tipo: si todavía no lo tenía, lo toma de la OT.
create or replace function public.recordar_tipo_unidad()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  update public.unidades set tipo = new.tipo where id = new.unidad_id and tipo is null;
  return new;
end $$;

create trigger ot_recordar_tipo
  after insert on public.ordenes_trabajo
  for each row execute function public.recordar_tipo_unidad();

-- Tarea: renglón automático; descripción y horas desde el tempario.
create or replace function public.antes_de_guardar_tarea()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_tarea text; v_horas numeric;
begin
  if new.tempario_id is not null then
    select tarea, horas into v_tarea, v_horas from public.tempario where id = new.tempario_id;
    new.descripcion := coalesce(nullif(trim(new.descripcion), ''), v_tarea);
    new.horas := coalesce(new.horas, v_horas);
  end if;
  new.horas := coalesce(new.horas, 0);
  if coalesce(trim(new.descripcion), '') = '' then
    raise exception 'La tarea necesita una descripción';
  end if;
  if tg_op = 'INSERT' and new.renglon is null then
    select coalesce(max(renglon), 0) + 1 into new.renglon from public.tareas_ot where ot_id = new.ot_id;
  end if;
  return new;
end $$;

create trigger tarea_antes_de_guardar
  before insert or update on public.tareas_ot
  for each row execute function public.antes_de_guardar_tarea();

-- Asignación: solo usuarios con rol Mecánico, y como máximo dos por tarea.
create or replace function public.controlar_asignacion()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from public.usuario_roles where usuario_id = new.mecanico_id and rol = 'MECANICO') then
    raise exception 'Solo se pueden asignar usuarios con rol Mecánico';
  end if;
  if (select count(*) from public.asignaciones where tarea_id = new.tarea_id and mecanico_id <> new.mecanico_id) >= 2 then
    raise exception 'Una tarea puede tener como máximo dos mecánicos';
  end if;
  return new;
end $$;

create trigger asignacion_controlar
  before insert or update on public.asignaciones
  for each row execute function public.controlar_asignacion();

-- Repuesto en OT: controla stock (si no alcanza, no deja cargar).
create or replace function public.controlar_stock_repuesto_ot()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_disponible numeric; v_ot bigint;
begin
  if new.tarea_id is not null then
    select ot_id into v_ot from public.tareas_ot where id = new.tarea_id;
    if v_ot is distinct from new.ot_id then
      raise exception 'La tarea no pertenece a esa OT';
    end if;
  end if;
  -- Bloquea el repuesto para que dos cargas simultáneas no pasen el stock.
  perform 1 from public.repuestos where codigo = new.codigo for update;
  v_disponible := public.stock_de(new.codigo);
  if tg_op = 'UPDATE' and old.codigo = new.codigo then
    v_disponible := v_disponible + old.cantidad;
  end if;
  if new.cantidad > v_disponible then
    raise exception 'Stock insuficiente de %: disponible %, pedido %',
      new.codigo, public.num_texto(v_disponible), public.num_texto(new.cantidad)
      using errcode = 'P0001', hint = 'STOCK_INSUFICIENTE';
  end if;
  if tg_op = 'UPDATE' then
    new.modificado_por := auth.uid();
    new.modificado_en := now();
  end if;
  return new;
end $$;

create trigger repuesto_ot_controlar_stock
  before insert or update on public.repuestos_ot
  for each row execute function public.controlar_stock_repuesto_ot();

-- Repuesto en OT: genera la SALIDA de stock; si se corrige o se borra, el stock vuelve.
-- Si quien modifica o quita no es Oficina ni Administrador, avisa a ambos.
create or replace function public.movimiento_repuesto_ot()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_desc text; v_numero integer; v_nombre text;
begin
  if tg_op = 'INSERT' then
    insert into public.movimientos_stock (tipo, codigo, cantidad, ot_id, repuesto_ot_id, usuario_id)
    values ('SALIDA', new.codigo, new.cantidad, new.ot_id, new.id, auth.uid());
    return new;
  end if;

  select numero into v_numero from public.ordenes_trabajo where id = coalesce(new.ot_id, old.ot_id);
  select nombre into v_nombre from public.usuarios where id = auth.uid();

  if tg_op = 'UPDATE' then
    update public.movimientos_stock
       set codigo = new.codigo, cantidad = new.cantidad
     where repuesto_ot_id = new.id;
    if not public.es_oficina_o_admin() and (new.cantidad <> old.cantidad or new.codigo <> old.codigo) then
      select descripcion into v_desc from public.repuestos where codigo = new.codigo;
      insert into public.avisos (para_rol, tipo, mensaje, ot_id)
      select r, 'REPUESTO MODIFICADO',
             format('%s modificó un repuesto en %s: %s (%s), cantidad %s → %s',
                    coalesce(v_nombre, 'Un usuario'), public.numero_ot_texto(v_numero),
                    v_desc, new.codigo, public.num_texto(old.cantidad), public.num_texto(new.cantidad)),
             new.ot_id
      from unnest(array['OFICINA', 'ADMINISTRADOR']::public.rol_usuario[]) r;
    end if;
    return new;
  end if;

  -- DELETE: el movimiento de salida se borra solo (el stock vuelve).
  if not public.es_oficina_o_admin() and auth.uid() is not null then
    select descripcion into v_desc from public.repuestos where codigo = old.codigo;
    insert into public.avisos (para_rol, tipo, mensaje, ot_id)
    select r, 'REPUESTO QUITADO',
           format('%s quitó un repuesto de %s: %s (%s), cantidad %s',
                  coalesce(v_nombre, 'Un usuario'), public.numero_ot_texto(v_numero),
                  v_desc, old.codigo, public.num_texto(old.cantidad)),
           old.ot_id
    from unnest(array['OFICINA', 'ADMINISTRADOR']::public.rol_usuario[]) r
    where exists (select 1 from public.ordenes_trabajo where id = old.ot_id);
  end if;
  return old;
end $$;

