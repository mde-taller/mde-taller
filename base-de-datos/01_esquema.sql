-- ---------------------------------------------------------------------
-- 8. Stock (movimientos)
-- ---------------------------------------------------------------------
-- El stock disponible no se guarda: es la suma de los movimientos.
--   STOCK INICIAL, ENTRADA  → suman      SALIDA → resta      AJUSTE → suma o resta
create table public.movimientos_stock (
  id              bigint generated by default as identity primary key,
  fecha           timestamptz not null default now(),
  tipo            public.tipo_movimiento not null,
  codigo          text not null references public.repuestos (codigo) on update cascade,
  cantidad        numeric(12,2) not null,
  ot_id           bigint references public.ordenes_trabajo (id) on delete cascade,
  repuesto_ot_id  bigint unique references public.repuestos_ot (id) on delete cascade,
  usuario_id      uuid references public.usuarios (id) default auth.uid(),
  usuario_nombre  text,          -- solo para movimientos traídos del Excel
  observacion     text,          -- remito, proveedor o motivo
  constraint cantidad_valida check (
    (tipo = 'AJUSTE' and cantidad <> 0) or (tipo <> 'AJUSTE' and cantidad > 0)
  )
);
create index movimientos_codigo on public.movimientos_stock (codigo);

-- Número legible para mensajes: 2.50 → "2,5", 10.00 → "10"
create or replace function public.num_texto(v numeric)
returns text language sql immutable as $$
  select replace(case when position('.' in v::text) > 0
                      then rtrim(rtrim(v::text, '0'), '.') else v::text end, '.', ',');
$$;

create or replace function public.stock_de(p_codigo text)
returns numeric language sql stable security definer set search_path = public as $$
  select coalesce(sum(case tipo when 'SALIDA' then -cantidad else cantidad end), 0)
  from public.movimientos_stock where codigo = p_codigo;
$$;

create view public.stock_disponible with (security_invoker = true) as
select r.codigo,
       r.descripcion,
       coalesce(sum(m.cantidad) filter (where m.tipo = 'STOCK INICIAL'), 0) as stock_inicial,
       coalesce(sum(m.cantidad) filter (where m.tipo = 'ENTRADA'), 0)       as entradas,
       coalesce(sum(m.cantidad) filter (where m.tipo = 'SALIDA'), 0)        as salidas,
       coalesce(sum(m.cantidad) filter (where m.tipo = 'AJUSTE'), 0)        as ajustes,
       coalesce(sum(case m.tipo when 'SALIDA' then -m.cantidad else m.cantidad end), 0) as disponible
from public.repuestos r
left join public.movimientos_stock m on m.codigo = r.codigo
group by r.codigo, r.descripcion;

